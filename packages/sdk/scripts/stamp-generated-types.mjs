#!/usr/bin/env node
/**
 * Stamp the generated-types file with a `@provenance` header.
 *
 * `openapi-typescript` always emits its own fixed banner, so this script
 * prepends a provenance comment mirroring the `src/provenance.ts` constants.
 * It is idempotent: running it twice does not duplicate the header.
 *
 * Part of `pnpm generate:types` so committed output and CI regeneration
 * stay byte-identical.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const target = resolve(__dirname, "..", "src", "generated-types.ts");

const header = `/**
 * @provenance
 * tool: openapi-typescript
 * toolVersion: ^7.4.3
 * source: web/tests/fixtures/openapi.snapshot.json
 * pkg: @talos-protocol/sdk
 *
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */
`;

let content = readFileSync(target, "utf8");
// Strip the tool's default banner and any previously stamped header, then
// re-stamp so repeated runs are idempotent.
content = content.replace(/^\/\*\*[\s\S]*?\*\/\s*/, "");
writeFileSync(target, header + content, "utf8");
console.log("[stamp-generated-types] @provenance header applied");
